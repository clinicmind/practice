import { build } from 'esbuild';
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

/**
 * Bundles each Edge Function (`reports` with the de-identification scanner, `ai-feedback` with the AI checks) into ONE file.
 * The owner pastes that file into the Supabase web editor, which cannot be relied on to
 * resolve imports from other files. Run: `npm run functions`.
 */
const root = join(dirname(fileURLToPath(import.meta.url)), '..');
export const REPORTS_ENTRY = join(root, 'supabase', 'functions', 'reports', 'src', 'entry.ts');
export const REPORTS_OUT = join(root, 'supabase', 'functions', 'reports', 'index.ts');

export const AI_FEEDBACK_ENTRY = join(root, 'supabase', 'functions', 'ai-feedback', 'src', 'entry.ts');
export const AI_FEEDBACK_OUT = join(root, 'supabase', 'functions', 'ai-feedback', 'index.ts');

const BANNER = `// 由程式產生，不要手改。GENERATED by scripts/build-functions.ts. Do not edit by hand.
// Source: supabase/functions/reports/src/ and packages/deid/src/. Rebuild with: npm run functions
// Paste this whole file into the Supabase Edge Function editor. See docs/SETUP-reports.md.
`;

async function bundle(entry: string, banner: string): Promise<string> {
  const r = await build({
    entryPoints: [entry],
    bundle: true,
    write: false,
    format: 'esm',
    platform: 'neutral',
    target: 'es2022',
    charset: 'utf8', // some rules and prompts contain Chinese characters; keep them readable
    legalComments: 'none',
    logLevel: 'silent',
  });
  // The handler and the pure checks are exported so a test can compare the bundle with the original.
  return banner + r.outputFiles[0]!.text;
}

export const bundleReportsFunction = () => bundle(REPORTS_ENTRY, BANNER);

const AI_BANNER = `// 由程式產生，不要手改。GENERATED by scripts/build-functions.ts. Do not edit by hand.
// Source: supabase/functions/ai-feedback/src/ and packages/ai-feedback/src/. Rebuild with: npm run functions
// Paste this whole file into the Supabase Edge Function editor. See docs/SETUP-ai.md.
`;
export const bundleAiFeedbackFunction = () => bundle(AI_FEEDBACK_ENTRY, AI_BANNER);

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  for (const [out, text] of [[REPORTS_OUT, await bundleReportsFunction()], [AI_FEEDBACK_OUT, await bundleAiFeedbackFunction()]] as const) {
    mkdirSync(dirname(out), { recursive: true });
    writeFileSync(out, text);
    console.log(`wrote ${out} (${text.length} characters)`);
  }
}
