import { build } from 'esbuild';
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

/**
 * Bundles the `reports` Edge Function, with the de-identification scanner, into ONE file.
 * The owner pastes that file into the Supabase web editor, which cannot be relied on to
 * resolve imports from other files. Run: `npm run functions`.
 */
const root = join(dirname(fileURLToPath(import.meta.url)), '..');
export const REPORTS_ENTRY = join(root, 'supabase', 'functions', 'reports', 'src', 'entry.ts');
export const REPORTS_OUT = join(root, 'supabase', 'functions', 'reports', 'index.ts');

const BANNER = `// 由程式產生，不要手改。GENERATED by scripts/build-functions.ts. Do not edit by hand.
// Source: supabase/functions/reports/src/ and packages/deid/src/. Rebuild with: npm run functions
// Paste this whole file into the Supabase Edge Function editor. See docs/SETUP-reports.md.
`;

export async function bundleReportsFunction(): Promise<string> {
  const r = await build({
    entryPoints: [REPORTS_ENTRY],
    bundle: true,
    write: false,
    format: 'esm',
    platform: 'neutral',
    target: 'es2022',
    charset: 'utf8', // the scanner's rules contain Chinese characters; keep them readable
    legalComments: 'none',
    logLevel: 'silent',
  });
  // The scanner and the handler are exported so a test can compare the bundle with the original.
  return BANNER + r.outputFiles[0]!.text;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const out = await bundleReportsFunction();
  mkdirSync(dirname(REPORTS_OUT), { recursive: true });
  writeFileSync(REPORTS_OUT, out);
  console.log(`wrote ${REPORTS_OUT} (${out.length} characters)`);
}
