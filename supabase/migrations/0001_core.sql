-- ClinicMind Practice: core schema (phase 2).
-- Authorisation is decided here, by row level security. The front end makes no
-- authorisation decisions. Every table has RLS enabled; no policy means no access.

-- Supabase grants broad default privileges to anon/authenticated. Start from nothing.
alter default privileges in schema public revoke all on tables from anon, authenticated;
alter default privileges in schema public revoke all on functions from anon, authenticated;
alter default privileges in schema public revoke all on sequences from anon, authenticated;

-- ---------------------------------------------------------------- tables

create table cohorts (
  id            uuid primary key default gen_random_uuid(),
  name          text not null check (char_length(btrim(name)) between 1 and 80),
  supervisor_id uuid not null references auth.users (id) on delete restrict,
  invite_code   text not null unique,
  term_end      date not null,
  created_at    timestamptz not null default now()
);

create table profiles (
  id           uuid primary key references auth.users (id) on delete cascade,
  role         text not null default 'student' check (role in ('student', 'supervisor')),
  display_name text not null check (display_name = btrim(display_name) and char_length(display_name) between 1 and 40),
  cohort_id    uuid references cohorts (id) on delete set null,
  created_at   timestamptz not null default now()
);

-- client_id is generated by the browser; (user_id, client_id) makes import idempotent.
create table attempts (
  id           uuid primary key default gen_random_uuid(),
  user_id      uuid not null default auth.uid() references auth.users (id) on delete cascade,
  client_id    uuid not null,
  item_id      text not null,
  response     text not null,
  criteria_met boolean[] not null check (array_length(criteria_met, 1) = 3),
  created_at   timestamptz not null default now(),
  unique (user_id, client_id)
);
create index attempts_user_idx on attempts (user_id, created_at);

create table decisions (
  id          uuid primary key default gen_random_uuid(),
  user_id     uuid not null default auth.uid() references auth.users (id) on delete cascade,
  client_id   uuid not null,
  session_id  text not null,
  decision_id text not null,
  option_id   text,
  response    text,
  created_at  timestamptz not null default now(),
  unique (user_id, client_id)
);
create index decisions_user_idx on decisions (user_id, created_at);

create table reflections (
  id          uuid primary key default gen_random_uuid(),
  user_id     uuid not null default auth.uid() references auth.users (id) on delete cascade,
  client_id   uuid not null,
  module_slug text not null,
  prompt_id   text not null,
  text        text not null,
  created_at  timestamptz not null default now(),
  unique (user_id, client_id)
);
create index reflections_user_idx on reflections (user_id, created_at);

create table unlocks (
  id          uuid primary key default gen_random_uuid(),
  user_id     uuid not null references auth.users (id) on delete cascade,
  module_slug text not null,
  level       text not null check (level in ('easy', 'medium', 'hard')),
  granted_by  uuid not null references auth.users (id),
  created_at  timestamptz not null default now(),
  unique (user_id, module_slug, level)
);

-- Never holds response text: who did what to which row, and when.
create table audit_log (
  id           uuid primary key default gen_random_uuid(),
  actor_id     uuid,
  action       text not null,
  target_table text not null,
  target_id    uuid,
  created_at   timestamptz not null default now()
);

-- Failed join attempts, for the per-account rate limit. Only join_cohort touches it.
create table join_attempts (
  id         bigint generated always as identity primary key,
  user_id    uuid not null,
  created_at timestamptz not null default now(),
  ok         boolean not null
);
create index join_attempts_user_idx on join_attempts (user_id, created_at);

alter table cohorts       enable row level security;
alter table profiles      enable row level security;
alter table attempts      enable row level security;
alter table decisions     enable row level security;
alter table reflections   enable row level security;
alter table unlocks       enable row level security;
alter table audit_log     enable row level security;
alter table join_attempts enable row level security;   -- no policy, no grant: closed to everyone but definer functions

-- ---------------------------------------------------------------- helpers

-- Used by policies. Security definer so reading profiles/cohorts here does not
-- recurse into their own policies.
create function is_supervisor_of(student uuid) returns boolean
language sql stable security definer set search_path = public, pg_temp as $$
  select exists (
    select 1
    from profiles s
    join cohorts c on c.id = s.cohort_id
    where s.id = student and c.supervisor_id = auth.uid()
  )
$$;

-- Role and cohort are written only by security definer functions or by the
-- project owner. This trigger holds even if a column privilege were widened.
create function guard_profile_update() returns trigger
language plpgsql set search_path = public, pg_temp as $$
begin
  if current_user in ('authenticated', 'anon')
     and (new.role is distinct from old.role or new.cohort_id is distinct from old.cohort_id or new.id is distinct from old.id) then
    raise exception 'role and cohort cannot be changed' using errcode = '42501';
  end if;
  return new;
end $$;

create trigger profiles_guard before update on profiles
  for each row execute function guard_profile_update();

-- ---------------------------------------------------------------- policies

-- profiles: read own; supervisors read their cohort's students. No insert/delete
-- policy: rows are created by join_cohort or by the project owner.
create policy profiles_select on profiles for select to authenticated
  using (id = auth.uid() or is_supervisor_of(id));
create policy profiles_update_own on profiles for update to authenticated
  using (id = auth.uid()) with check (id = auth.uid());

-- cohorts: supervisors read their own (including the invite code). Students
-- have no access, so they never see the code. Writes only via create_cohort.
create policy cohorts_select on cohorts for select to authenticated
  using (supervisor_id = auth.uid());

-- attempts / decisions / reflections: insert and select only.
create policy attempts_select on attempts for select to authenticated
  using (user_id = auth.uid() or is_supervisor_of(user_id));
create policy attempts_insert on attempts for insert to authenticated
  with check (user_id = auth.uid());

create policy decisions_select on decisions for select to authenticated
  using (user_id = auth.uid() or is_supervisor_of(user_id));
create policy decisions_insert on decisions for insert to authenticated
  with check (user_id = auth.uid());

create policy reflections_select on reflections for select to authenticated
  using (user_id = auth.uid() or is_supervisor_of(user_id));
create policy reflections_insert on reflections for insert to authenticated
  with check (user_id = auth.uid());

-- unlocks: student reads own; supervisor reads and grants for own cohort's students.
create policy unlocks_select on unlocks for select to authenticated
  using (user_id = auth.uid() or is_supervisor_of(user_id));
create policy unlocks_insert on unlocks for insert to authenticated
  with check (is_supervisor_of(user_id) and granted_by = auth.uid());

-- audit_log: supervisors read their own actions. Written only by definer code.
create policy audit_select on audit_log for select to authenticated
  using (actor_id = auth.uid());

-- ---------------------------------------------------------------- privileges

grant select on profiles, cohorts, attempts, decisions, reflections, unlocks, audit_log to authenticated;
grant insert on attempts, decisions, reflections, unlocks to authenticated;
grant update (display_name) on profiles to authenticated;   -- not role, not cohort_id

-- ---------------------------------------------------------------- functions

-- Returns (cohort_id, error_code). Failures are RETURNED, not raised: a raised
-- exception would roll back the failed-attempt row that the rate limit counts.
-- error_code: invalid_display_name | invalid_code | cohort_closed | rate_limited
create function join_cohort(code text, display_name text)
returns table (cohort_id uuid, error_code text)
language plpgsql security definer set search_path = public, pg_temp as $$
#variable_conflict use_column
declare
  uid uuid := auth.uid();
  name_clean text := btrim(coalesce(display_name, ''));
  norm text := upper(btrim(coalesce(code, '')));
  found cohorts%rowtype;
  existing profiles%rowtype;
  failures int;
begin
  if uid is null then
    raise exception 'not authenticated' using errcode = '28000';
  end if;

  if char_length(name_clean) not between 1 and 40 then
    return query select null::uuid, 'invalid_display_name'::text;
    return;
  end if;

  select count(*) into failures from join_attempts j
   where j.user_id = uid and not j.ok and j.created_at > now() - interval '1 hour';
  if failures >= 10 then
    return query select null::uuid, 'rate_limited'::text;
    return;
  end if;

  select * into found from cohorts c where c.invite_code = norm;
  if found.id is null then
    insert into join_attempts (user_id, ok) values (uid, false);
    return query select null::uuid, 'invalid_code'::text;
    return;
  end if;

  if found.term_end < current_date then
    return query select null::uuid, 'cohort_closed'::text;
    return;
  end if;

  select * into existing from profiles p where p.id = uid;
  if existing.id is not null then
    -- Already has a profile: no-op. Students keep their first cohort and
    -- supervisors stay supervisors.
    return query select existing.cohort_id, null::text;
    return;
  end if;

  insert into profiles (id, role, display_name, cohort_id) values (uid, 'student', name_clean, found.id);
  insert into join_attempts (user_id, ok) values (uid, true);
  return query select found.id, null::text;
end $$;

create function create_cohort(name text, term_end date)
returns table (id uuid, invite_code text)
language plpgsql security definer set search_path = public, pg_temp as $$
#variable_conflict use_column
declare
  uid uuid := auth.uid();
  alphabet constant text := 'ABCDEFGHJKLMNPQRSTUVWXYZ23456789';   -- 32 chars, no 0 O 1 I l
  new_code text;
  new_id uuid;
  tries int := 0;
  bytes bytea;
  i int;
begin
  if uid is null or not exists (select 1 from profiles p where p.id = uid and p.role = 'supervisor') then
    raise exception 'only supervisors can create cohorts' using errcode = '42501';
  end if;
  if char_length(btrim(coalesce(name, ''))) not between 1 and 80 then
    raise exception 'invalid cohort name' using errcode = '22023';
  end if;
  if term_end is null or term_end < current_date then
    raise exception 'term end must not be in the past' using errcode = '22023';
  end if;

  loop
    -- 10 bytes of gen_random_uuid() (skipping the version/variant bytes); 256 % 32 = 0, so no bias.
    bytes := decode(replace(gen_random_uuid()::text, '-', ''), 'hex');
    new_code := '';
    for i in 0..9 loop
      new_code := new_code || substr(alphabet, (get_byte(bytes, case when i < 6 then i else i + 3 end) % 32) + 1, 1);
    end loop;
    begin
      insert into cohorts (name, supervisor_id, invite_code, term_end)
      values (btrim(name), uid, new_code, term_end)
      returning cohorts.id into new_id;
      exit;
    exception when unique_violation then
      tries := tries + 1;
      if tries > 5 then raise; end if;
    end;
  end loop;

  insert into audit_log (actor_id, action, target_table, target_id)
  values (uid, 'create_cohort', 'cohorts', new_id);

  return query select new_id, new_code;
end $$;

revoke all on function is_supervisor_of(uuid) from public;
revoke all on function join_cohort(text, text) from public;
revoke all on function create_cohort(text, date) from public;
grant execute on function is_supervisor_of(uuid) to authenticated;
grant execute on function join_cohort(text, text) to authenticated;
grant execute on function create_cohort(text, date) to authenticated;
